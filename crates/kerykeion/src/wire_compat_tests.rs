//! Wire-compatibility skeleton for the reimplemented `meshtastic` protobuf
//! schema (`proto/*.proto`).
//!
//! WHY this file is separate from the self-roundtrip tests in `lib.rs`:
//! encoding a message with THIS crate's own `prost`-generated code and then
//! decoding it with the SAME code only proves the schema is internally
//! consistent — it cannot prove the field numbers/wire types actually match
//! a real Meshtastic device, because a bug that flips two field numbers
//! would round-trip against itself perfectly while being wire-incompatible
//! with everything else. That can only be proven against bytes this crate
//! did not produce: a frame captured from a real radio (serial/TCP,
//! stripped of the 4-byte `MeshCodec` header — see `src/codec.rs`), or
//! against the reference Python/JS Meshtastic client.
//!
//! STATUS: unverified. No capture fixture exists yet. Each `#[ignore]`d
//! test below documents the exact assertion a real fixture must satisfy;
//! replace the `todo!()` fixture loader with real captured bytes (e.g.
//! checked in under `proto/fixtures/`, or generated by pairing
//! with a device over serial) and remove `#[ignore]` to turn this from a
//! skeleton into a real gate.

