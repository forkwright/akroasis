/// A `FromRadio` carrying a plain text message, captured from a real
/// device, must decode with the exact field values the capture is known
/// to contain.
///
/// Fill in the expected `from`/`to`/`id`/portnum/payload bytes from
/// whatever fixture `load_fixture("text_message.bin")` ends up loading —
/// the asserts below are placeholders naming WHAT must hold, not values
/// pulled from this schema's own assumptions.
#[test]
#[ignore = "needs a real captured frame; see module doc"]
fn from_radio_text_message_decodes_against_real_capture() {
    let bytes = load_fixture("text_message.bin");

    #[expect(clippy::unwrap_used, reason = "fixture is known-valid once wired")]
    let decoded = FromRadio::decode(bytes.as_slice()).unwrap();

    let Some(from_radio::PayloadVariant::Packet(packet)) = decoded.payload_variant else {
        panic!("expected FromRadio::Packet, got {decoded:?}");
    };

    // WHY placeholders: these must be replaced with the capture's actual
    // values once `load_fixture` is real — a passing assert against a
    // value this schema invented would prove nothing.
    assert_eq!(packet.from, 0, "replace with the capture's real `from`");
    assert_eq!(packet.to, 0, "replace with the capture's real `to`");
}

/// A `MeshPacket` this crate encodes must be byte-identical to what a
/// captured real packet with the SAME field values looks like — i.e. this
/// schema's field numbers and wire types match the real protocol, not
/// just each other.
///
/// This is the strongest form of proof this schema can offer without a
/// live device: it does not just decode a capture, it re-encodes a packet
/// built from that capture's known field VALUES and checks the bytes
/// match, catching a field-number swap that happened to still decode.
#[test]
#[ignore = "needs a real captured frame; see module doc"]
fn mesh_packet_encode_matches_real_capture_bytes() {
    let expected_bytes = load_fixture("mesh_packet_known_values.bin");

    // WHY: construct the SAME logical packet the capture is known to
    // encode, using this schema's types, then compare bytes rather than
    // decoded fields — this is the direction that actually exercises our
    // field numbers instead of prost's own symmetry.
    //
    // TODO(#388): set every field below to the capture's real values
    // (from, to, id, hop_limit, priority, decoded portnum/payload, ...)
    // before removing `#[ignore]`.
    let packet = MeshPacket::default();

    let mut encoded = Vec::new();
    #[expect(clippy::unwrap_used, reason = "encoding a well-formed message cannot fail")]
    packet.encode(&mut encoded).unwrap();

    assert_eq!(
        encoded, expected_bytes,
        "encoded bytes must match the real device's capture exactly, \
         not just round-trip against this crate's own decoder"
    );
}
